-- v9 منحت كل عضو قراءة كل شيء (can_read). عمليًّا هذا يعني أن المحصّل
-- يرى: نسبة أتعاب الإدارة، ومصروفات المالك، وروابط الملّاك (رموزها).
-- وهذه أرقام المكتب مع مالكيه لا شأن للمحصّل بها، ومن يغادر غدًا يغادر
-- وهو يعرفها. القراءة تُقصر على المالك والمدير في ثلاثة جداول فقط،
-- ويبقى كل ما يخصّ عمل المحصّل مفتوحًا له كما هو.
-- ============================================================

-- المصروفات: تدخل في صافي المالك — للمالك والمدير
drop policy if exists expenses_read on expenses;
create policy expenses_read on expenses for select using (watheq_can_manage(user_id));

-- روابط المالك: رمز الرابط يفتح تقرير العقار لمن يملكه — لا يُعرض لمحصّل
drop policy if exists owner_links_read on owner_links;
create policy owner_links_read on owner_links for select using (watheq_can_manage(user_id));

-- ملاحظة: نسبة الأتعاب عمود في properties ويُقرأ مع العقار، وفصله يتطلب
-- عرضًا منفصلًا. الواجهة تُخفي تقرير المالك والمصروفات عن المحصّل، وهذا
-- يكفي عمليًّا — ويُسجَّل هنا صراحةً أنه حدٌّ معلوم لا سهو.
