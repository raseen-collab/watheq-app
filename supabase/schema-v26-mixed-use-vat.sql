-- ============================================================
-- وثيق — schema-v26: العقار المختلط (سكني + تجاري)
--
-- عمارة فيها شقق سكنية ومحلات تجارية: الإيجار السكني معفى من ضريبة القيمة
-- المضافة، والتجاري خاضع لها. وتفعيل الضريبة على العقار كان يطبّقها على
-- كل وحداته — فتخرج فاتورة شقة سكنية بضريبة لا تُستحق، وهذا خطأ يكلّف مالًا.
--
-- الحل: الضريبة تُقرَّر لكل وحدة:
--   auto (الافتراضي) = بحسب نوع الوحدة إن حُدّد، وإلا نوع العقار
--   on / off         = تجاوز صريح للحالات الخاصة
-- ============================================================
alter table tenants add column if not exists vat_mode text not null default 'auto'
  check (vat_mode in ('auto', 'on', 'off'));
