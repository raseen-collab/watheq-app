-- وثيق — schema-v33: بيانات تجريبية للمسجّل الجديد
--
-- أغلب من يسجّل من إعلان لا وقت عنده لإدخال بيانات ليجرّب — فيغادر قبل أن
-- يرى شيئًا. البيانات التجريبية تعطيه لوحة حيّة من أول ثانية.
--
-- الخطر الوحيد اختلاطها ببياناته الحقيقية. فالقاعدة الصارمة:
--   • تُوسم بـ is_demo على العقار (والوحدات والدفعات تتبعه بالحذف المتسلسل)
--   • تُحذف كلها بضغطة واحدة، وتُحذف تلقائيًّا حين يضيف أول عقار حقيقي
--   • لا تدخل الملخّص اليومي ولا فحص السلامة ولا إحصاءات الإدارة
--   • لا تُنشأ إلا لحساب بلا أي عقار — فلا تكرار ولا عبث
-- ============================================================
alter table properties add column if not exists is_demo boolean not null default false;
create index if not exists properties_demo_idx on properties (user_id) where is_demo;
comment on column properties.is_demo is 'عقار تجريبي يُحذف مع وحداته ودفعاته بضغطة — لا يدخل التقارير التشغيلية';
