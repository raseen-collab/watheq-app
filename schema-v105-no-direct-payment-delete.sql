-- v105 — لا حذف مباشر للدفعات (25 نوفمبر 2026)
-- فحص المحاسب: سياسة payments_delete كانت تسمح لمن له «التراجع» بحذف صفّ دفعة
-- مباشرةً، فيختفي السند ولا ينقص «المحصَّل» — وهذا يشرح فرق 31,599 عند مكتب التميز.
-- التصحيح في وثيق يتم بالعكس (watheq_reverse_payment / undo / edit) ويبقى أثره في السجل.
-- لا شاشة في التطبيق تحذف دفعة مباشرة: حذف التجربة وحذف الحساب يتمّان بمفتاح
-- الخادم (يتجاوز السياسات) فلا يتأثران. صفوف التجربة (is_demo) تبقى قابلة للحذف.
-- تعديل سياسة فقط — لا حذف ولا تعديل بيانات.
-- ============================================================
alter policy payments_delete on public.payments
  using (is_demo is true and watheq_perm(user_id, 'undo_actions') and association_id is null and owner_id is null);
