/* ============================================================
   عامل الخدمة (Service Worker) — وثيق
   ------------------------------------------------------------
   غرضه واحد فقط: استيفاء شرط كروم لإظهار زر «تثبيت التطبيق»،
   وهو وجود مستمع fetch.

   ⚠️ لا يخزّن شيئًا عمدًا — كل طلب يمرّ إلى الشبكة كما هو.
   عامل خدمة يخزّن الصفحات يجعل المستخدم يرى نسخة قديمة من
   التطبيق بعد كل نشر، وتشخيص ذلك مؤلم. حين تحتاج العمل بلا
   إنترنت لاحقًا، يُضاف التخزين هنا بوعي لا بالافتراض.
   ============================================================ */

self.addEventListener("install", () => {
  // فعّل النسخة الجديدة فورًا بلا انتظار إغلاق التبويبات
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      // احذف أي مخزن قديم خلّفته نسخة سابقة
      const keys = await caches.keys();
      await Promise.all(keys.map((k) => caches.delete(k)));
      await self.clients.claim();
    })()
  );
});

self.addEventListener("fetch", (event) => {
  // تمرير صريح إلى الشبكة — بلا تخزين ولا اعتراض
  event.respondWith(fetch(event.request));
});
