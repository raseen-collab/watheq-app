/**
 * وثيق — fetch بلا ذاكرة مؤقتة لكل عميل Supabase على الخادم.
 *
 * Next 14 يخزّن نتائج fetch في «Data Cache» حتى داخل المسارات الديناميكية
 * أحيانًا (خصوصًا المسارات التي لا تقرأ cookies)، فيعيد استعلام القاعدة نفسه
 * بنتيجته القديمة. ظهر ذلك في رابط المالك (30 سبتمبر 2026): مستند صدر ولم
 * يظهر في الرابط لأن ردّ القاعدة الأول بقي محفوظًا. البيانات المالية لا
 * تُخزَّن مؤقتًا أبدًا.
 */
export const noStoreFetch: typeof fetch = (input: any, init?: any) =>
  fetch(input, { ...(init || {}), cache: "no-store" });
