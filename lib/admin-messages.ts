/**
 * وثيق — رسائل جاهزة لصاحب المنصة
 *
 * لماذا قوالب لا ذكاء اصطناعي: الرسالة التي تُرسل لعميل يجب أن تكون
 * صحيحة الأرقام والاسم والتاريخ في كل مرة، وأن تظهر فورًا بلا انتظار
 * ولا تكلفة. الذكاء الاصطناعي مكانه الخطة والتسويق (المستشار اليومي)،
 * لا الرسالة التشغيلية التي تتكرر يوميًّا بنفس الشكل.
 *
 * كل رسالة تُفتح بضغطة في واتساب مكتوبةً بالفعل — لا نسخ ولا لصق.
 */

export type MsgKind = "renew" | "hot_trial" | "expired" | "silent_new" | "gone_quiet" | "welcome";

export type MsgCtx = {
  name: string;            // اسم المكتب أو الشخص
  units?: number;
  props?: number;
  pays?: number;
  daysLeft?: number | null;
  endDate?: string | null;
  sinceJoin?: number | null;
  sinceLast?: number | null;
  plan?: string | null;
  price?: number | null;
};

const he = (n?: number | null) => (n && n > 0 ? n : 0);

export function buildMessage(kind: MsgKind, c: MsgCtx): { title: string; text: string } {
  const who = c.name?.trim() || "أستاذي";
  const units = he(c.units);

  switch (kind) {
    case "renew":
      return {
        title: "تجديد اشتراك",
        text:
`السلام عليكم ${who} 🌿

اشتراككم في وثيق ينتهي ${c.endDate ? `بتاريخ ${c.endDate}` : "قريبًا"}${c.daysLeft !== null && c.daysLeft !== undefined ? ` (بقي ${c.daysLeft} يوم)` : ""}.

للتجديد: ${c.price ? `${c.price} ريال` : "نفس الباقة"} شهريًا، ويستمر كل شيء كما هو — ${units ? `${units} وحدة` : "بياناتكم"} وسجلاتكم بلا انقطاع.

أرسل لي «جدّد» وأتولّى الباقي، وإن كان عندك أي ملاحظة على الخدمة قبل التجديد أنا أسمعك.`,
      };

    case "hot_trial":
      return {
        title: "تجربة تنتهي قريبًا",
        text:
`السلام عليكم ${who} 🌿

ملاحظة سريعة: تجربتكم في وثيق تنتهي ${c.daysLeft === 0 ? "اليوم" : `خلال ${c.daysLeft} يوم`}${c.endDate ? ` (${c.endDate})` : ""}.

شفت إنكم مدخلين ${c.props ? `${c.props} عقار و` : ""}${units} وحدة${c.pays ? ` ومسجّلين ${c.pays} دفعة` : ""} — يعني النظام صار جزءًا من شغلكم.

عشان ما ينقطع شيء: الاشتراك ${c.price ? `${c.price} ريال` : ""} شهريًا وبياناتكم تبقى كما هي.
أرسل لي «أكمل» وأفعّله لك اليوم.`,
      };

    case "expired":
      return {
        title: "انتهت التجربة",
        text:
`السلام عليكم ${who} 🌿

انتهت تجربتكم في وثيق${c.endDate ? ` بتاريخ ${c.endDate}` : ""}، وبياناتكم كلها محفوظة كما هي — ${units ? `${units} وحدة` : ""} وسجلاتها.

إذا حاب تكمل: أفعّل الاشتراك لك في دقيقة وترجع من نفس النقطة.
وإذا وقفت لسبب معيّن أو نقص فيه شيء تحتاجه، قل لي بصراحة — ملاحظتك تفيدني أكثر من الاشتراك نفسه.`,
      };

    case "silent_new":
      return {
        title: "سجّل ولم يبدأ",
        text:
`السلام عليكم ${who} 🌿

سجّلت في وثيق ${c.sinceJoin ? `قبل ${c.sinceJoin} يوم` : "مؤخرًا"} وما بدأت بعد — وأتوقّع السبب إن إدخال البيانات يبي وقت.

عرض بدون أي التزام: أرسل لي بيانات عقاراتك بأي شكل عندك (ملف إكسل، صورة دفتر، أو حتى رسالة) وأنا أجهّز لك الحساب كامل بنفسي خلال يوم — العقارات والوحدات والعقود والمسدَّد.

وبعدها تدخل وتشوف كل شي جاهز، وتقرّر.`,
      };

    case "gone_quiet":
      return {
        title: "توقّف بعد البداية",
        text:
`السلام عليكم ${who} 🌿

شفت إنك مدخل ${units} وحدة في وثيق، وآخر نشاط ${c.sinceLast ? `قبل ${c.sinceLast} يوم` : "له فترة"}.

سؤال واحد بصراحة: فيه شيء وقفك أو ناقصك؟ أنا المطوّر نفسه وأقدر أضيف أو أعدّل بسرعة، وإذا الموضوع وقت أجهّز لك أي شيء ناقص بنفسي.`,
      };

    case "welcome":
      return {
        title: "ترحيب بمسجّل جديد",
        text:
`السلام عليكم ${who} 🌿

أهلًا بك في وثيق — أنا عبيد، مطوّر المنصة، وتواصلك معي مباشر بدون دعم فني.

إذا حاب أوفّر عليك وقت الإدخال: أرسل لي بيانات عقاراتك بأي شكل وأجهّز لك الحساب كامل خلال يوم، بدون التزام.
وإذا واجهك أي شيء اكتب لي هنا مباشرة.`,
      };
  }
}

/** رابط واتساب برسالة مكتوبة مسبقًا — ضغطة واحدة بلا نسخ ولا لصق */
export function waSend(phone: string, text: string): string {
  return `https://wa.me/${phone}?text=${encodeURIComponent(text)}`;
}
