const OUT_OF_SCOPE = [
  "ضريبة الدخل", "زكاة", "تأشيرة", "إقامة", "كفالة", "راتب موظف",
  "طلاق", "ميراث", "جنائي", "مخدرات", "سلاح",
];

export type RiskLevel = "normal" | "high" | "out";

export function classify(question: string): RiskLevel {
  const q = String(question || "");
  if (OUT_OF_SCOPE.some((k) => q.includes(k))) return "out";
  if (HIGH_RISK.some((k) => q.includes(k))) return "high";
  return "normal";
}

