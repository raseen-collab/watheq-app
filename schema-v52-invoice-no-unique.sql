-- وثيق — شبكة أمان الترقيم (v52) · 28 سبتمبر 2026
--
-- v51 أصلح السبب: العدّاد صار يتقدّم فعلًا (مُثبَت: 16 → 17).
-- هذا الملف يضيف الطبقة الثانية: القاعدة نفسها ترفض رقمًا مكرَّرًا،
-- مهما كان سبب التكرار ومهما تغيّر الكود لاحقًا.
--
-- الفواتير القديمة تبقى كما هي بلا مساس — الفهرس جزئي، يسري على ما
-- يصدر من ٢٩ سبتمبر ٢٠٢٦ فصاعدًا فقط. الـ٤٦ فاتورة المكرَّرة تبقى
-- في السجل بأرقامها وتواريخها، ولا يُعاد ترقيمها ولا تُحذف.
--
-- آمن للتشغيل أكثر من مرة.
-- ══════════════════════════════════════════════════════════════════

begin;

-- الرقم فريد داخل المكتب الواحد، لا بين المكاتب: لكل مكتب عدّاده.
create unique index if not exists invoices_user_no_uniq
  on public.invoices (user_id, invoice_no)
  where issue_date >= date '2026-09-29';

comment on index public.invoices_user_no_uniq is
  'رقم الفاتورة فريد لكل مكتب. جزئي من 2026-09-29 لأن ما قبله يحوي تكرارًا '
  'من عطل عدّاد الفواتير (الحارس trg_guard_profile_columns كان يلغي الزيادة). '
  'أُصلح السبب في v51 — والفواتير القديمة تُركت عمدًا كما صدرت.';

commit;

-- ══════════════════════════════════════════════════════════════════
-- الفحص
-- ══════════════════════════════════════════════════════════════════
select 'الفهرس' as البند,
       case when exists (
         select 1 from pg_indexes
         where schemaname = 'public' and indexname = 'invoices_user_no_uniq')
       then 'موجود ✅' else 'غير موجود ❌' end as الحالة
union all
select 'تكرار بعد 29 سبتمبر',
       coalesce((select count(*)::text from (
         select 1 from public.invoices
         where issue_date >= date '2026-09-29'
         group by user_id, invoice_no having count(*) > 1) x), '0') || ' (يجب أن يكون 0)'
union all
select 'فواتير قديمة محفوظة',
       (select count(*)::text from public.invoices where issue_date < date '2026-09-29')
       || ' فاتورة — لم تُمسّ';
